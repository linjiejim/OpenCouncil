export interface ExpandableWork {
  /** Thinker slug (must already exist in the DB seed). */
  slug: string;
  /** Committed data file under ./data that this work appends into. */
  dataFile: string;
  thinkerName: string;
  tradition: string;
  /** Fetch the verbatim text for a backlog ref. */
  fetch: (ref: string) => Promise<FetchedText>;
  /** Chapter labels (+ optional integrity anchor) for a backlog ref. */
  label: (ref: string) => Curated;
  /** Map a backlog ref to the canonicalRef the fetcher will stamp — for pre-fetch
   *  frontier diffing against the existing file (so we never re-fetch what's in). */
  refToCanonical: (ref: string) => string;
  /** Ordered candidate refs. Already-collected ones are filtered out by the expander. */
  backlog: () => string[];
}

