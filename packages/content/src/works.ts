//   • Sequentially-numbered canons (Dhammapada 1–423, Daodejing 1–81) can be
//     walked HANDS-OFF: the next un-collected verse is always safe to fetch.
//   • Large / imperfectly-aligned canons (Quran, Gospels, Analects) use a
