/**
 * A curated reference. Provide editorial metadata to author it by hand
 * (metadataSource = "editorial"); omit it to have the metadata generated by the
 * LLM (metadataSource = model name). The sourced text is fetched either way.
 */
export interface Curated {
  ref: string; // verse number (Dhp) or "S:V" (Quran) or "Book C:V" (Gospel) or "B.C" (Analects)
  chapterEn: string;
  chapterZh: string;
  chapterOrig?: string;
  /** Integrity anchor: the fetched original MUST contain this substring, else the
   *  item is dropped. Guards against source-parse misalignment/truncation. */
  expectContains?: string;
  summaryEn?: string;
  summaryZh?: string;
  similarQuestions?: string[];
  contextNote?: string;
  tags?: string[];
  weight?: number;
}

/** Run `fn` over items with bounded concurrency, preserving input order. */
export async function mapPool<T, R>(items: T[], limit: number, fn: (item: T, i: number) => Promise<R>): Promise<R[]> {
  const out = new Array<R>(items.length);
  let next = 0;
  async function worker() {
    while (next < items.length) {
      const i = next++;
      out[i] = await fn(items[i], i);
    }
  }
  await Promise.all(Array.from({ length: Math.min(limit, items.length) }, worker));
  return out;
}

